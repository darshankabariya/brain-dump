#!/usr/bin/env python3
# Build the index of this topic from index.json: writes index.html (a standalone
# landing page you can open from disk) and replaces the block between
# <!-- index:start --> and <!-- index:end --> in README.md (what GitHub renders).
# Run from the topic directory:
#     python3 tools/build_index.py
import html
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
reg = json.load(open(os.path.join(root, "index.json"), encoding="utf-8"))

KIND_CLASS = {
    "study page": "page", "study page + animation": "anim", "step animation": "anim",
    "interactive explainer": "anim", "NotebookLM source": "doc", "brief": "doc",
    "video": "video", "notes": "doc", "data": "data", "tools": "data",
}


def esc(s):
    return html.escape(s or "", quote=True)


# ---------- README block ----------
def md_block():
    out = []
    out.append("<!-- index:start -->")
    out.append("<!-- generated by tools/build_index.py from index.json; edit those, not this block -->")
    out.append("")
    out.append("Registry updated %s. Open `index.html` for the same list as a page with links." % reg["updated"])
    out.append("")
    for sec in reg["sections"]:
        out.append("### " + sec["title"])
        out.append("")
        out.append("| what | kind | file | published page | updated | status |")
        out.append("|---|---|---|---|---|---|")
        for e in sec["entries"]:
            pub = "[page](%s)" % e["published"] if e.get("published") else "—"
            ver = (" (%s)" % e["version"]) if e.get("version") else ""
            out.append("| **%s** | %s | [`%s`](./%s) | %s | %s%s | %s |" % (
                e["title"], e["kind"], e["file"], e["file"], pub, e["updated"], ver, e["status"]))
        out.append("")
        for e in sec["entries"]:
            line = "- **%s** — %s" % (e["title"], e["learn"])
            if e.get("notes"):
                line += " _%s_" % e["notes"]
            out.append(line)
        out.append("")
    if reg.get("excluded"):
        out.append("Not in this index: " + " ".join(reg["excluded"]))
        out.append("")
    if reg.get("corrections"):
        out.append("### Corrections log")
        out.append("")
        out.append("| date | what | state |")
        out.append("|---|---|---|")
        for c in reg["corrections"]:
            out.append("| %s | %s | %s |" % (c["date"], c["what"], c["state"]))
        out.append("")
    out.append("<!-- index:end -->")
    return "\n".join(out)


readme_path = os.path.join(root, "README.md")
readme = open(readme_path, encoding="utf-8").read()
start, end = "<!-- index:start -->", "<!-- index:end -->"
if start not in readme or end not in readme:
    print("README.md has no index markers; add <!-- index:start --> and <!-- index:end -->", file=sys.stderr)
    sys.exit(1)
pre = readme[: readme.index(start)]
post = readme[readme.index(end) + len(end):]
open(readme_path, "w", encoding="utf-8").write(pre + md_block() + post)
print("wrote README.md index block")


