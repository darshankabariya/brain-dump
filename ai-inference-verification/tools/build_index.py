def card(e):
    kc = KIND_CLASS.get(e["kind"], "page")
    is_dir = e["file"].endswith("/")
    links = ['<a href="./%s">%s</a>' % (esc(e["file"]), "open folder" if is_dir else "open local file")]
    if e.get("published"):
        links.append('<a class="pub" href="%s" target="_blank" rel="noopener">published page</a>' % esc(e["published"]))
    status_cls = "status" + ("" if e["status"] == "current" else " warn")
    ver = (" · " + esc(e["version"])) if e.get("version") else ""
    notes = ('<div class="notes">%s</div>' % esc(e["notes"])) if e.get("notes") else ""
    return """<div class="card">
  <div><span class="pill %s">%s</span></div>
  <h3>%s</h3>
  <p>%s</p>
  %s
  <div class="meta"><span>first %s</span><span>updated %s%s</span></div>
  <div class="%s">status: %s</div>
  <div class="links">%s</div>
</div>""" % (kc, esc(e["kind"]), esc(e["title"]), esc(e["learn"]), notes, esc(e["first"]), esc(e["updated"]), ver, status_cls, esc(e["status"]), "".join(links))


